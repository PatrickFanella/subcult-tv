"""Web assets for the Kork product (code name zelda), from the Kork pack artwork.

Writes brands/kork/product/: favicon.svg, apple-touch-icon.png (180),
hero.svg (pinned cards, transparent) and og.png (1200x630, no URL so it
stays valid if the domain changes). Text is converted to paths so browsers
render the SVGs without the pack fonts.
"""
from pathlib import Path
import json, os, subprocess
R = Path(__file__).resolve().parent
os.environ['FONTCONFIG_FILE'] = str(R / 'fontconfig.xml')
import design_helpers as H
d = next(b for b in json.loads((R / 'brands.json').read_text()) if b['slug'] == 'kork')
OUT = R.parent / 'brands/kork/product'
OUT.mkdir(parents=True, exist_ok=True)

def outlined(name, body, w, h):
    raw = OUT / f'.{name}.raw.svg'; raw.write_text(H.svg(body, w, h, f'Kork {name}'))
    dest = OUT / f'{name}.svg'
    subprocess.run(['inkscape', str(raw), '--export-text-to-path', '--export-plain-svg', '--export-type=svg', '--export-filename=' + str(dest)], check=True, capture_output=True)
    raw.unlink()
    return dest

def png(svg, name, w):
    subprocess.run(['rsvg-convert', '-w', str(w), '-o', str(OUT / name), str(svg)], check=True)

outlined('favicon', H.corkboard_mark(d, 0, 0, 160), 160, 160)
icon = outlined('.apple-touch-icon', H.rect(0, 0, 180, 180, d['bg']) + H.corkboard_mark(d, 20, 20, 140), 180, 180)
png(icon, 'apple-touch-icon.png', 180); icon.unlink()
outlined('hero', H.cork_stack(d, 10, 24, 520, 270), 540, 310)
og = H.rect(0, 0, 1200, 630, d['bg']) + H.cork_texture(1200, 630)
og += H.corkboard_mark(d, 64, 60, 96) + H.txt(180, 132, 'kork', 64, d['fg'], d['display'], 700)
for i, text in enumerate(d['headline_stack']):
    og += H.txt(64, 290 + i * 92, text, 84, d['fg'], d['display'], 700, maxw=600)
og += H.txt(64, 540, 'Socials, payments, QR codes and more on one page.', 26, d['fg'], d['body'], maxw=600)
og += H.cork_stack(d, 690, 150, 470, 330)
ogsvg = outlined('.og', og, 1200, 630); png(ogsvg, 'og.png', 1200); ogsvg.unlink()
(OUT / 'README.md').write_text('# Kork product web assets\n\nGenerated by `kork_product_assets.py` from the Kork pack artwork for the links-page service (code name zelda). Text is outlined. `og.png` deliberately omits a URL. Copy these files into the product; regenerate here instead of editing the copies.\n')
print(sorted(p.name for p in OUT.iterdir()))
