"""Web assets for Prichal (managed AT Protocol PDS hosting), from the Prichal pack artwork.

Writes brands/prichal/product/: favicon.svg, apple-touch-icon.png (180),
hero.svg (docking node with drawing details, transparent) and og.png
(1200x630, no URL so it stays valid if the domain changes). Text is converted
to paths so browsers render the SVGs without the pack fonts.
"""
from pathlib import Path
import json, os, subprocess
R = Path(__file__).resolve().parent
os.environ['FONTCONFIG_FILE'] = str(R / 'fontconfig.xml')
import design_helpers as H
d = next(b for b in json.loads((R / 'brands.json').read_text()) if b['slug'] == 'prichal')
OUT = R / 'brands/prichal/product'
OUT.mkdir(parents=True, exist_ok=True)
RULE = '#c9c4b6'

def outlined(name, body, w, h):
    raw = OUT / f'.{name}.raw.svg'; raw.write_text(H.svg(body, w, h, f'Prichal {name}'))
    dest = OUT / f'{name}.svg'
    subprocess.run(['inkscape', str(raw), '--export-text-to-path', '--export-plain-svg', '--export-type=svg', '--export-filename=' + str(dest)], check=True, capture_output=True)
    raw.unlink()
    return dest

def png(svg, name, w):
    subprocess.run(['rsvg-convert', '-w', str(w), '-o', str(OUT / name), str(svg)], check=True)

outlined('favicon', H.docking_mark(d, 0, 0, 160), 160, 160)
icon = outlined('.apple-touch-icon', H.rect(0, 0, 180, 180, d['bg']) + H.docking_mark(d, 18, 18, 144), 180, 180)
png(icon, 'apple-touch-icon.png', 180); icon.unlink()
hero = H.drawing_ticks(0, 20, 300, RULE) + H.docking_mark(d, 60, 20, 300) + H.line(40, 344, 520, 344, RULE, 2) + H.port_strip(d, 40, 374, 15)
outlined('hero', hero, 540, 390)
og = H.rect(0, 0, 1200, 630, d['bg']) + H.drawing_ticks(24, 60, 500, RULE)
og += H.txt(80, 104, 'ПРИЧАЛ · ACCOUNT HOSTING', 20, d['safe_label'], d['label'])
og += H.txt(80, 250, 'PRICHAL', 132, d['fg'], d['display'], 700, maxw=600)
og += H.rect(80, 282, 200, 7, d['accent'])
og += H.txt(80, 372, 'Your server.', 52, d['fg'], d['body'], 700, maxw=620) + H.txt(80, 436, 'We keep it running.', 52, d['fg'], d['body'], 700, maxw=620)
og += H.txt(80, 506, 'Account hosting for the open social web.', 26, d['fg'], d['body'], maxw=620)
og += H.docking_mark(d, 760, 140, 340)
og += H.line(80, 560, 1120, 560, RULE, 2) + H.port_strip(d, 80, 594, 18)
ogsvg = outlined('.og', og, 1200, 630); png(ogsvg, 'og.png', 1200); ogsvg.unlink()
(OUT / 'README.md').write_text('# Prichal product web assets\n\nGenerated by `prichal_product_assets.py` from the Prichal pack artwork. Text is outlined. `og.png` deliberately omits a URL. Copy these files into the product or site; regenerate here instead of editing the copies.\n')
print(sorted(p.name for p in OUT.iterdir()))
